-- =====================================================================
--  رقم فيديو فيسبوك — مُعرّف ثابت للمطابقة
--
--  رابط المشاركة (share/v/<رمز>) يتغيّر كل مرة يُعاد فيها مشاركة الفيديو،
--  فلا يصلح لكشف التكرار. رقم الفيديو ثابت. تحلّه دالة fb-lookup عند
--  الضغط على «جِب البيانات»، فنخزّنه ونطابق عليه.
-- =====================================================================

alter table public.entries
  add column if not exists fb_id text;

create index if not exists entries_fb_id_idx on public.entries (fb_id) where fb_id is not null;
